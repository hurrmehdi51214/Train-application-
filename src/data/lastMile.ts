const MIN = 60_000;

function departures(startInMinutes: number, everyMinutes: number, count = 4): string[] {
  const now = Date.now();
  return Array.from({ length: count }, (_, i) =>
    new Date(Math.round((now + (startInMinutes + i * everyMinutes) * MIN) / MIN) * MIN).toISOString(),
  );
}

