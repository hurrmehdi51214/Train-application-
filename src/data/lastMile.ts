import type { LastMileOption } from '@/types';

/**
 * Last-mile connections from each station.
 *
 * Real services: Karachi's People's Bus Route network, the Lahore and
 * Rawalpindi-Islamabad Metrobus lines, Peshawar's BRT (Zu Peshawar), Multan
 * Metrobus, and the rickshaw and ride-hailing options that actually do most of
 * the work at every other station.
 *
 * Against a configured gateway these come from the city transit feeds and the
 * Google Directions transit mode; see `services/googleMaps.ts`. The shape is
 * identical either way.
 */

const MIN = 60_000;

function departures(startInMinutes: number, everyMinutes: number, count = 4): string[] {
  const now = Date.now();
  return Array.from({ length: count }, (_, i) =>
    new Date(Math.round((now + (startInMinutes + i * everyMinutes) * MIN) / MIN) * MIN).toISOString(),
  );
}

